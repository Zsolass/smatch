import type { ClinicImage } from "@/config/clinic";

interface Props {
  image: ClinicImage;
  sizes: string;
  className?: string;
  priority?: boolean;
  /** Overrides the configured alternative text (use "" when the picture is decorative here). */
  alt?: string;
}

/** Responsive WebP image with reserved dimensions; below-the-fold images load lazily. */
export function Picture({ image, sizes, className = "", priority = false, alt }: Props) {
  const srcSet = image.widths.map((w) => `${image.src}-${w}.webp ${w}w`).join(", ");
  const largest = image.widths.at(-1)!;
  return (
    // eslint-disable-next-line @next/next/no-img-element -- static export; the srcset is generated by scripts/render
    <img
      src={`${image.src}-${largest}.webp`}
      srcSet={srcSet}
      sizes={sizes}
      width={largest}
      height={Math.round(largest / image.aspect)}
      alt={alt ?? image.alt}
      loading={priority ? "eager" : "lazy"}
      fetchPriority={priority ? "high" : "auto"}
      decoding="async"
      className={className}
    />
  );
}
